import {chromium} from 'playwright';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import {spawn} from 'node:child_process';
import assert from 'node:assert/strict';
const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'thv-browser-'));
const web=path.join(tmp,'public_html');
fs.mkdirSync(web);fs.mkdirSync(path.join(tmp,'thv-private'));
for(const name of fs.readdirSync('.'))if(!name.startsWith('.')&&!['node_modules','tests','package.json','package-lock.json'].includes(name))fs.cpSync(name,path.join(web,name),{recursive:true});
const key=crypto.randomBytes(24).toString('hex');
fs.writeFileSync(path.join(tmp,'thv-private','setup.key'),key);
const prep=path.join(tmp,'https.php');
fs.writeFileSync(prep,"<?php $_SERVER['HTTPS']='on';");
const origin='http://localhost:18765';
const server=spawn('php',['-d','auto_prepend_file='+prep,'-S','127.0.0.1:18765','-t',web],{stdio:'ignore'});
let browser;
try{
 await new Promise(r=>setTimeout(r,800));
 browser=await chromium.launch({headless:true,args:['--no-sandbox'],...(process.env.STUDIO_BROWSER?{executablePath:process.env.STUDIO_BROWSER}:{})});
 const page=await browser.newPage({viewport:{width:1600,height:1000},bypassCSP:true});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(origin+'/vereinsbereich.php');
 await page.locator('[name=key]').fill(key);
 await page.locator('[name=name]').fill('Test Redaktion');
 await page.locator('[name=email]').fill('editor@example.invalid');
 await page.locator('[name=password]').fill('testpass-1234567890');
 await page.getByRole('button',{name:'Einrichten',exact:true}).click();
 await page.getByRole('link',{name:/Website Studio/}).first().click();
 await page.waitForFunction(()=>document.getElementById('studio-message')?.textContent.startsWith('Bereit.'));
 await page.locator('#page-list').getByRole('button',{name:'Welpen und Junghunde',exact:true}).click();
 await page.waitForFunction(()=>document.getElementById('preview')?.contentWindow?.location.pathname.endsWith('/welpen.html')&&!!document.getElementById('preview')?.contentWindow?.thvStudioApply);
 const iframe=page.frameLocator('#preview');
 const heading=iframe.locator('h1[data-studio-field]');
 const original=await heading.textContent();
 await heading.click();
 await page.locator('#text').fill('Welpen und Junghunde Test');
 await page.waitForFunction(()=>document.getElementById('preview').contentDocument.querySelector('h1[data-studio-field]').textContent==='Welpen und Junghunde Test');
 await page.waitForFunction(()=>document.getElementById('studio-message').textContent.includes('Automatisch gespeichert'),null,{timeout:15000});
 await page.locator('#undo').click();
 assert.equal(await heading.textContent(),original);
 await page.locator('#redo').click();
 assert.equal(await heading.textContent(),'Welpen und Junghunde Test');
 await page.locator('#font-style').selectOption('italic');
 await page.locator('#text-align').selectOption('center');
 assert.equal(await heading.evaluate(el=>el.style.textAlign),'center');
 await heading.dblclick();
 await heading.fill('Direkt bearbeitet');
 await heading.press('Control+Enter');
 await page.waitForFunction(()=>document.getElementById('text').value==='Direkt bearbeitet');
 await page.locator('[data-studio-tab=blocks]').click();
 await page.locator('[data-add-block=cta]').click();
 await page.locator('#block-title').fill('Test Kontaktaktion');
 await page.locator('#block-body').fill('Absatz eins\n\nAbsatz zwei');
 await page.waitForFunction(()=>document.getElementById('preview').contentDocument.querySelector('.studio-added-section h2')?.textContent==='Test Kontaktaktion');
 await page.locator('#mobile').click();
 await page.waitForFunction(()=>document.getElementById('preview').clientWidth<=390);
 await page.locator('#clean-preview').click();
 assert.equal(await page.locator('#clean-preview').getAttribute('aria-pressed'),'true');
 await page.locator('#clean-preview').click();
 await page.locator('#desktop').click();
 await page.waitForFunction(()=>!document.getElementById('publish').disabled);
 page.once('dialog',d=>d.accept());
 await page.locator('#publish').click();
 await page.waitForFunction(()=>document.getElementById('studio-message').textContent.includes('veröffentlicht'),null,{timeout:15000});
 const anon=await browser.newPage({bypassCSP:true});
 await anon.goto(origin+'/welpen.html');
 await anon.waitForFunction(()=>document.querySelector('h1[data-studio-field]')?.textContent==='Direkt bearbeitet');
 assert.equal(await anon.locator('.studio-added-section h2').textContent(),'Test Kontaktaktion');
 assert.equal(await anon.locator('.studio-added-section a.btn').getAttribute('href'),'kontakt.html');
 await anon.close();
 assert.deepEqual(errors,[]);
 console.log('PASS: visual editing, autosave, undo/redo, typography, inline editing, content blocks, mobile preview, publishing');
}finally{await browser?.close();server.kill();fs.rmSync(tmp,{recursive:true,force:true});}
